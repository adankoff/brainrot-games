/**
 * Shuffle an array in-place using Fisher-Yates.
 * @param {Array} arr
 * @returns {Array} The same array, shuffled.
 */
export function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Build a game question queue. Picks questions by ascending difficulty,
 * shuffled within each difficulty band.
 *
 * @returns {Array} Ordered question list for one game session.
 */
export function buildQuestionQueue() {
  const byDifficulty = { 1: [], 2: [], 3: [] };

  for (const q of questions) {
    const d = q.difficulty;
    if (byDifficulty[d]) {
      byDifficulty[d].push({ ...q });
    }
  }

  shuffle(byDifficulty[1]);
  shuffle(byDifficulty[2]);
  shuffle(byDifficulty[3]);

  // First 5 from easy, next 5 from medium, rest from hard, then cycle
  const queue = [
    ...byDifficulty[1].slice(0, 5),
    ...byDifficulty[2].slice(0, 5),
    ...byDifficulty[3],
    ...byDifficulty[1].slice(5),
    ...byDifficulty[2].slice(5),
  ];

  return queue;
}
